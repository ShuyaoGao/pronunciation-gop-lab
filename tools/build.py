# -*- coding: utf-8 -*-
"""One command to build the static page data (play/data/app_data.js) and the release zip.

    python -m tools.build              # app_data.js + credits.js
    python -m tools.build --release    # ... and release/<repo>-v<version>.zip (play/ + root index.html)

Inputs (all in data/): sentences.json + g2p_sentences.json (pre-computed phonemes),
model_vocab.json, thresholds.json, thresholds_legacy.json, l2_hints_en.json, calibration_report.md.
Pure Python standard library — no model, no audio.
"""

import argparse
import json
import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
PLAY = ROOT / "play"
RELEASE = ROOT / "release"
ZIP_LIMIT = 15 * 1024 * 1024


def load(name):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def parse_calibration_report(text):
    """Pull the numbers out of data/calibration_report.md (the source shown on the page)."""
    def num(rx):
        m = re.search(rx, text)
        return float(m.group(1)) if m else None
    groups = {}
    for name, key in (("发对", "good"), ("发错", "bad")):
        m = re.search(r"\|\s*" + name + r"\([^)]*\)\s*\|\s*(\d+)\s*\|\s*([-\d.]+)\s*\|\s*([-\d.]+)\s*\|\s*([-\d.]+)\s*\|\s*([-\d.]+)\s*\|", text)
        if m:
            groups[key] = {"n": int(m.group(1)), "mean": float(m.group(2)), "p25": float(m.group(3)),
                           "median": float(m.group(4)), "p75": float(m.group(5))}
    per_phone = []
    for m in re.finditer(r"^\|\s*/([^/]+)/\s*\|\s*(\d+)\s*\|\s*([-\d.]+)\s*\|\s*([-\d.]+)\s*\|\s*([-\d.]+)\s*\|\s*([-\d.]+)\s*\|\s*([-\d.]+)\s*\|\s*([-\d.]+)\s*\|", text, re.M):
        per_phone.append({"ipa": m.group(1), "n": int(m.group(2)), "mean": float(m.group(3)), "p25": float(m.group(4)),
                          "median": float(m.group(5)), "p75": float(m.group(6)), "expert_mean": float(m.group(7)),
                          "good_minus_bad": float(m.group(8))})
    return {"auc": num(r"AUC[^=]*=\s*([\d.]+)"), "pearson": num(r"Pearson\(GOP, 专家分\)\s*=\s*([-\d.]+)"),
            "spearman": num(r"Spearman\s*=\s*([-\d.]+)"), "minutes": num(r"推理耗时：([\d.]+)\s*分钟"),
            "middle_excluded": num(r"中间分\s*(\d+)\s*个"), "groups": groups, "per_phone": per_phone}


def build_app_data():
    vocab = load("model_vocab.json")
    g2p = load("g2p_sentences.json")
    sents = load("sentences.json")
    for level, items in sents.items():
        if level.startswith("_"):
            continue
        got = [s["text"] for s in g2p["levels"].get(level, [])]
        if got != items:
            raise SystemExit(f"data/g2p_sentences.json is stale for {level}: run `python -m tools.export_g2p`")
    th, legacy = load("thresholds.json"), load("thresholds_legacy.json")
    report = (DATA / "calibration_report.md").read_text(encoding="utf-8")
    cal = parse_calibration_report(report)
    data = {
        "vocab": {"order": vocab["vocab_order"], "blank": vocab["blank_id"], "size": vocab["size"], "model_id": vocab["model_id"]},
        "sentences": g2p["levels"], "g2p_en_version": g2p.get("g2p_en_version"),
        "thresholds": {k: v for k, v in th.items() if not k.startswith("_")},
        "thresholds_legacy": {k: v for k, v in legacy.items() if not k.startswith("_")},
        "hints": {k: v for k, v in load("l2_hints_en.json").items() if not k.startswith("_")},
        "calibration": cal,
    }
    out = PLAY / "data" / "app_data.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("/* Generated by tools/build.py from data/*.json and data/calibration_report.md -- do not edit. */\n"
                   "window.APP_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    return out, data


def load_credits():
    for p in (ROOT / "credits.json", ROOT / "tools" / "credits.default.json"):
        if p.exists():
            return json.loads(p.read_text(encoding="utf-8"))
    raise FileNotFoundError("credits.json not found")


def write_credits_js(credits):
    keep = {k: v for k, v in credits.items() if not k.startswith("_")}
    out = PLAY / "js" / "credits.js"
    out.write_text("/* Generated by tools/build.py from credits.json -- edit credits.json, then rebuild. */\n"
                   "window.CREDITS = " + json.dumps(keep, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
    return out


def root_index():
    """The root entry page (meta refresh -> play/index.html): the rendered one in the repository root, or the
    template, so that "unzip, double-click index.html" works for the release zip."""
    for p in (ROOT / "index.html", ROOT / "tools" / "publish_templates" / "index.html.tmpl"):
        if p.exists():
            return p
    return None


def make_zip(credits):
    RELEASE.mkdir(exist_ok=True)
    out = RELEASE / f"{credits.get('REPO_NAME', 'pronunciation-gop-lab')}-v{credits.get('VERSION', '1.0')}.zip"
    entries = [("play/" + p.relative_to(PLAY).as_posix(), p.read_bytes()) for p in sorted(PLAY.rglob("*")) if p.is_file()]
    idx = root_index()
    if idx is not None:
        html = idx.read_text(encoding="utf-8")
        for k, v in credits.items():
            html = html.replace("{{" + k + "}}", str(v))
        entries.insert(0, ("index.html", html.encode("utf-8")))
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name, data in entries:
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    size = out.stat().st_size
    if size > ZIP_LIMIT:
        raise SystemExit(f"release zip is {size} bytes > 15 MB")
    return out, size, len(entries)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--release", action="store_true")
    args = ap.parse_args(argv)
    out, data = build_app_data()
    print(f"wrote {out.relative_to(ROOT)}: {sum(len(v) for v in data['sentences'].values())} sentences, "
          f"{len(data['calibration']['per_phone'])} calibrated phones")
    print("wrote", write_credits_js(load_credits()).relative_to(ROOT))
    total = sum(p.stat().st_size for p in PLAY.rglob("*") if p.is_file())
    print(f"play/ = {total} bytes")
    if args.release:
        z, size, n = make_zip(load_credits())
        print(f"wrote {z.relative_to(ROOT)}: {n} files, {size} bytes")


if __name__ == "__main__":
    main()
