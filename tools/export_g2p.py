# -*- coding: utf-8 -*-
"""Pre-compute the canonical phonemes of every sentence in data/sentences.json with the
project's own G2P (src/g2p.py = g2p_en + ARPABET->IPA), so the browser page needs no G2P.

    python -m tools.export_g2p        # needs g2p_en (pip install g2p_en) -> data/g2p_sentences.json

The browser version only covers these sentences; free text needs the full Python version.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
OUT = ROOT / "data" / "g2p_sentences.json"


def main():
    import importlib.metadata as md
    from g2p import G2P
    g = G2P()
    sents = json.loads((ROOT / "data" / "sentences.json").read_text(encoding="utf-8"))
    out = {"_note": "Generated by `python -m tools.export_g2p` (src/g2p.py: g2p_en + ARPABET->IPA). "
                    "Do not edit by hand.",
           "g2p_en_version": md.version("g2p_en"), "levels": {}}
    for level, items in sents.items():
        if level.startswith("_"):
            continue
        out["levels"][level] = []
        for text in items:
            phones = [{"ipa": p.ipa, "arpabet": p.arpabet, "word": p.word, "word_index": p.word_index,
                       "stress": p.stress, "is_vowel": p.is_vowel} for p in g.phonemize(text)]
            out["levels"][level].append({"text": text, "phones": phones})
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    n = sum(len(v) for v in out["levels"].values())
    print(f"wrote {OUT.relative_to(ROOT)}: {n} sentences")


if __name__ == "__main__":
    main()
